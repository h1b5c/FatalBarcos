CREATE OR REPLACE TRIGGER TRG_RESTRINGE_IDADE_BARCOS
    BEFORE INSERT OR UPDATE ON BARCO
    FOR EACH ROW
DECLARE
    v_menor_idade exception;
BEGIN
    IF (not Maior_Dezoito(:New.Data_FABRICACAO))
    then 
       raise  v_menor_idade;
    end if;
exception 
    when v_menor_idade then 
        RAISE_APPLICATION_ERROR (-20067, 'BARCO MUITO NOVO');
    when others then
        RAISE_APPLICATION_ERROR (-20069, 'ERRO NAO IDENTIFICADO');
END TRG_RESTRINGE_IDADE;
/

