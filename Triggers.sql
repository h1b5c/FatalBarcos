CREATE OR REPLACE TRIGGER TRG_BAIXA_ESTOQUE
BEFORE INSERT ON SESSAO_PRODUTO FOR EACH ROW
DECLARE
    V_ESTOQUE NUMBER;
BEGIN

    SELECT ESTOQUE
    INTO V_ESTOQUE
    FROM PRODUTO_SERVICO
    WHERE ID_PRODUTO = :NEW.ID_PRODUTO;

    IF V_ESTOQUE < :NEW.QNT THEN
        RAISE_APPLICATION_ERROR(-20001,'ESTOQUE INSUFICIENTE');
    END IF;

    UPDATE PRODUTO_SERVICO
    SET ESTOQUE = ESTOQUE - :NEW.QNT
    WHERE ID_PRODUTO = :NEW.ID_PRODUTO;

END;
/


CREATE OR REPLACE TRIGGER TRG_QTD_BARCOS
AFTER INSERT ON BARCO
FOR EACH ROW
BEGIN
    UPDATE DONO
    SET QNT_BARCOS = QNT_BARCOS + 1
    WHERE ID_DONO = :NEW.ID_DONO;
END;
